def put(path,text):
    path.parent.mkdir(parents=True,exist_ok=True);path.write_bytes(text.encode('utf-8'))

def load(path,name):
    spec=importlib.util.spec_from_file_location(name,path);module=importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module);return module

def emit_flash(p,data):
    # Reuse the unchanged UART loader's eviction, whole-DDR CRC, FENCE.I and jump.
    p.org(0xe40);p.label('flash_dispatch')
    p.branch('bne',31,0,'flash_poll');p.li(31,1)
    p.addi(22,6,0);p.addi(23,11,0);p.addi(24,12,0)
    p.li(16,0xf0001100);p.la(3,'loader_fault');p.writecsr(0x305,3)
    p.li(19,0xedb88320);p.li(2,0x40100000);p.li(4,len(data));p.addi(5,2,0)
    p.li(6,zlib.crc32(data));p.li(7,0x20000000+FLASH_OFFSET)
    p.addi(10,2,0);p.addi(8,4,0)
    p.label('flash_copy')
    p.load('lw',17,7);p.store(17,10);p.addi(7,7,4);p.addi(10,10,4)
    p.addi(8,8,-4);p.branch('bne',8,0,'flash_copy')
    p.li(10,0x40008000);p.li(8,32);p.jump('loader_evict')
    p.label('flash_poll')
    p.raw(0xf0001837,'original first uart_poll instruction: lui x16,0xf0001')
    p.li(3,0x864);p.i(0x67,0,0,3,0,'continue original uart_poll after its LUI')
    assert p.pc<=0x1000,hex(p.pc)

def make_boot(data):
    # This source branch is saved, rather than modifying the proven UART generator.
    original=W/'vexriscv_linux_test/ddr_integration/generate_boot.py'
    source=original.read_text(encoding='utf-8')
    source=source.replace("q.label('entry')","q.label('entry'); q.li(31, 0)",1)
    source=source.replace('    emit_serial_loader(p)\n','    emit_serial_loader(p)\n    emit_flash(p)\n',1)
    namespace={'__name__':'flash_candidate','__file__':str(original),'emit_flash':lambda p:emit_flash(p,data)}
    exec(compile(source,str(original),'exec'),namespace)
    payload=namespace['make_payload']();p=namespace['make_rom'](payload)
    assert p.words[0x860][0]==0xf0001837
    # Patch exactly one instruction; the fallback restores it before continuing.
    del p.words[0x860]
    p.pc=0x860;p.jump('flash_dispatch');p.finish()
    words=[p.words.get(i*4,(0x13,''))[0] for i in range(1024)]
    rom=(BASE/'vexriscv_b_boot_rom.v').read_text()
    rom=re.sub(r"rom_words\[(\d+)\] = 32'h[0-9a-f]+;",
               lambda match:f"rom_words[{match[1]}] = 32'h{words[int(match[1])]^0x13:08x};",rom)
    rom=rom.replace('//   Generated by vexriscv_linux_test/ddr_integration/generate_boot.py.',
                    '//   U33 candidate generated by firmware/linux_flash_u33/build.py.')
    return rom,p,words

def main():
    R.mkdir(parents=True,exist_ok=True);C.mkdir(parents=True,exist_ok=True)
    frozen=json.loads((W/'reports/linux_boot_20261020/before.json').read_text())
    protected=[W/n for n in frozen]
    protected += [PROJECT,W/'vexriscv_linux_test/ddr_integration/generate_boot.py']
    protected += [A/'td_project/camera_to_dsi_display.al',A/'user_source/hdl_source/design_top_wrapper.v',
                  A/'td_project/import/npu_u33_mcu_bridge.v']
    protected += list((A/'user_source/ip_source/MCU').glob('*'))
    snapshot={str(p):hashlib.sha256(p.read_bytes()).hexdigest() for p in protected if p.is_file()}
    before=R/'protected_before.json'
    if before.exists():
        assert json.loads(before.read_text())==snapshot,'Protected inputs changed; review before rebuilding'
    else:put(before,json.dumps(snapshot,indent=2))
    m=json.loads((W/'firmware/linux_boot/build/manifest.json').read_text())
    data=(W/'firmware/linux_boot/build/linux_uart.bin').read_bytes()
    assert len(data)==m['records']['linux_uart.bin']['bytes']
    assert hashlib.sha256(data).hexdigest()==m['records']['linux_uart.bin']['sha256']
    assert len(data)%4==0 and FLASH_OFFSET+len(data)<=MCU_OFFSET
    (O/'linux_payload.bin').write_bytes(data)
    rom,p,words=make_boot(data)
    put(C/'vexriscv_b_boot_rom.v',rom)
    put(O/'boot_program.hex',''.join(f'{word:08x}\n' for word in words))
    put(O/'boot_program.lst',''.join(f'{at:08x} {word:08x} {text}\n' for at,(word,text) in sorted(p.words.items())))
    put(O/'rom_labels.json',json.dumps(p.labels,indent=2))

    subsystem=(BASE/'vexriscv_b_subsystem.v').read_text()
    subsystem=subsystem.replace('parameter UART_ENABLE =',"parameter U33_FLASH_ENABLE = 1'b0,\n    parameter UART_ENABLE =",1)
    ports='''input wire clk_ahb, input wire rst_ahb,
    input wire [1:0] mcu_htrans_i, input wire mcu_hwrite_i,
    input wire [30:0] mcu_haddr_i, input wire [2:0] mcu_hsize_i,
    input wire [31:0] mcu_hwdata_i, output wire [31:0] mcu_hrdata_o,
    output wire [1:0] mcu_hresp_o, output wire mcu_hready_o,
    '''
    subsystem=subsystem.replace('input  wire        clk,',ports+'input  wire        clk,',1)
    marker='    assign ibus_ack='
    pos=subsystem.index(marker)
    bridge='''    wire flash_selected, flash_ack, flash_error;
    wire [31:0] flash_data;
    assign flash_selected = U33_FLASH_ENABLE && dbus_adr[29:22] == 8'h20;
    generate if (U33_FLASH_ENABLE) begin : u33_flash_enabled
        cpu_u33_flash_bridge flash_bridge_inst (
            .clk(clk), .rst(rst), .clk_ahb(clk_ahb), .rst_ahb(rst_ahb),
            .cyc_i(dbus_cyc && flash_selected), .stb_i(dbus_stb && flash_selected),
            .we_i(dbus_we), .address_i(dbus_adr), .ack_o(flash_ack),
            .error_o(flash_error), .data_o(flash_data),
            .htrans_i(mcu_htrans_i), .hwrite_i(mcu_hwrite_i),
            .haddr_i(mcu_haddr_i), .hsize_i(mcu_hsize_i), .hwdata_i(mcu_hwdata_i),
            .hrdata_o(mcu_hrdata_o), .hresp_o(mcu_hresp_o), .hready_o(mcu_hready_o)
        );
    end else begin : u33_flash_disabled
        assign flash_ack=1'b0; assign flash_error=1'b0; assign flash_data=32'd0;
        assign mcu_hrdata_o=32'd0; assign mcu_hresp_o=2'b00; assign mcu_hready_o=1'b1;
    end endgenerate
'''
    subsystem=subsystem[:pos]+bridge+subsystem[pos:]
    for signal,value in [('dbus_ack','flash_ack'),('dbus_err','flash_error'),('dbus_read_data','flash_data')]:
        subsystem=subsystem.replace('assign '+signal+'=','assign '+signal+'=flash_selected ? '+value+' : ',1)
    subsystem=subsystem.replace('dbus_cyc && !dbus_ddr_selected','dbus_cyc && !dbus_ddr_selected && !flash_selected')
    subsystem=subsystem.replace('dbus_stb && !dbus_ddr_selected','dbus_stb && !dbus_ddr_selected && !flash_selected')
    put(C/'vexriscv_b_subsystem.v',subsystem)
    shutil.copyfile(F/'rtl/cpu_u33_flash_bridge.v',C/'cpu_u33_flash_bridge.v')

    top_path=W/'reports/black_video_20261019/f0/rtl/design_top_wrapper_video_read_probe.v'
    top=top_path.read_text(encoding='utf-8')
    a_top=(A/'user_source/hdl_source/design_top_wrapper.v').read_text(encoding='utf-8')
    mcu=a_top[a_top.index('    MCU u_npu_flash_mcu ('):a_top.index('    npu_u33_mcu_bridge #(')]
    mcu=mcu.replace('u_npu_flash_mcu','u_linux_flash_mcu').replace('S_u33_boot_rst','S_flash_mcu_rst')
    mcu=mcu.replace('S_ddr_clk','S_100m_clk')
    declarations='''    wire S_mcu_ahb_clk;
    wire [1:0] S_mcu_htrans, S_mcu_hresp;
    wire S_mcu_hwrite, S_mcu_hready;
    wire [30:0] S_mcu_haddr;
    wire [2:0] S_mcu_hsize, S_mcu_hburst;
    wire [3:0] S_mcu_hprot;
    wire S_mcu_hmastlock;
    wire [31:0] S_mcu_hwdata, S_mcu_hrdata;
    (* async_reg="true" *) reg [1:0] S_flash_mcu_reset_sync=2'b11;
    wire S_flash_mcu_rst;
    always @(posedge S_100m_clk)
        S_flash_mcu_reset_sync <= {S_flash_mcu_reset_sync[0],S_cpu_rst};
    assign S_flash_mcu_rst=S_cpu_rst || S_flash_mcu_reset_sync[1];
'''
    top=top.replace('    wire [31:0] S_cpu_cycle_count;',declarations+'\n'+mcu+'    wire [31:0] S_cpu_cycle_count;',1)
    # Existing top declaration order puts S_cpu_rst after the insertion: move it before new use.
    top=top.replace('    wire S_cpu_rst;\n','',1)
    top=top.replace('    wire S_mcu_ahb_clk;','    wire S_cpu_rst;\n    wire S_mcu_ahb_clk;',1)
    anchor='    ) u_vexriscv_linux ('
    assert anchor in top
    # Only the CPU instance has this exact parameter line immediately before its instance.
    start=top.rfind('vexriscv_b_subsystem #',0,top.index(anchor))
    assert start>=0
    part=top[start:]
    part=part.replace('vexriscv_b_subsystem #(','vexriscv_b_subsystem #(\n        .U33_FLASH_ENABLE (1\'b1),',1)
    # Handle the actual repository's newline between # and its parenthesis.
    if '.U33_FLASH_ENABLE' not in part:
        part=part.replace('vexriscv_b_subsystem #\n    (','vexriscv_b_subsystem #\n    (\n        .U33_FLASH_ENABLE (1\'b1),',1)
    assert '.U33_FLASH_ENABLE' in part
    connections='''
        .clk_ahb(S_mcu_ahb_clk), .rst_ahb(S_flash_mcu_rst),
        .mcu_htrans_i(S_mcu_htrans), .mcu_hwrite_i(S_mcu_hwrite),
        .mcu_haddr_i(S_mcu_haddr), .mcu_hsize_i(S_mcu_hsize), .mcu_hwdata_i(S_mcu_hwdata),
        .mcu_hrdata_o(S_mcu_hrdata), .mcu_hresp_o(S_mcu_hresp), .mcu_hready_o(S_mcu_hready),'''
    part=part.replace(anchor,anchor+connections,1);top=top[:start]+part
    put(C/'design_top_wrapper_video_read_probe.v',top)
    IP.mkdir(exist_ok=True)
    for item in (A/'user_source/ip_source/MCU').iterdir():
        if item.is_file():shutil.copyfile(item,IP/item.name)

    instructions=[0x800002b7,0x0002a303,0x00137313,0xfe030ce3,0x0042a383,
                  0x0003ae03,0x01c2a423,0xfe9ff06f]
    fw=b''.join(struct.pack('<I',word) for word in instructions)
    (O/'u33_boot_fw.bin').write_bytes(fw)
    # Same firmware reset vector and QSPI mux IP as the original A-board mechanism.
    put(O/'u33_boot_fw.lst','\n'.join(f'{0x20e00000+i*4:08x} {v:08x}' for i,v in enumerate(instructions))+'\n')

    project=PROJECT.read_text(encoding='utf-8-sig')
    replacements={BASE/'vexriscv_b_boot_rom.v':C/'vexriscv_b_boot_rom.v',
                  BASE/'vexriscv_b_subsystem.v':C/'vexriscv_b_subsystem.v',
                  top_path:C/'design_top_wrapper_video_read_probe.v'}
    project=re.sub(r'<File Path="([^"]+)"',lambda match:'<File Path="'+
                   replacements.get((PROJECT.parent/match[1]).resolve(),(PROJECT.parent/match[1]).resolve()).as_posix()+'"',project)
    new_name='camera_to_dsi_display_linux_flash'
    project=project.replace('<Name>camera_to_dsi_display_uart</Name>','<Name>'+new_name+'</Name>',1)
    def file_entry(path,order):
        return f'<File Path="{path.as_posix()}"><FileInfo><Attr Name="UsedInSyn" Val="true"/><Attr Name="UsedInP&R" Val="true"/><Attr Name="BelongTo" Val="design_1"/><Attr Name="CompileOrder" Val="{order}"/></FileInfo></File>\n'
    project=project.replace('</Verilog>',file_entry(C/'cpu_u33_flash_bridge.v',300)+'</Verilog>',1)
    project=project.replace('</IP_FILE>',file_entry(IP/'MCU.xml',301)+'</IP_FILE>',1)
    section=re.search(r'<SDC_FILE>(.*?)</SDC_FILE>',project,re.S)
    assert section,'Missing SDC source section'
    entry=file_entry(F/'u33_flash.sdc',302).replace('design_1','constraint_1')
    project=project.replace('</SDC_FILE>',entry+'</SDC_FILE>',1)
    put(W/'td_project'/ (new_name+'.al'),project)
    manifest=dict(status='CANDIDATE_NOT_PROGRAMMED',mechanism='U33 hard MCU XIP -> AHB read proxy -> VexRiscv existing DDR bus',
        flash_bytes=FLASH_SIZE,regions=[dict(name='FPGA configuration',offset=0,limit=FLASH_OFFSET,file='NEW_MATCHING_TD_BIN_REQUIRED'),
        dict(name='Linux SBI+kernel+initramfs',offset=FLASH_OFFSET,bytes=len(data),end=FLASH_OFFSET+len(data),sha256=hashlib.sha256(data).hexdigest(),crc32=f'{zlib.crc32(data):08x}'),
        dict(name='hard MCU firmware',offset=MCU_OFFSET,bytes=len(fw),reset_vector=0x20e00000,sha256=hashlib.sha256(fw).hexdigest())],
        load=0x40100000,entry=0x40100000,kernel=0x40400000,
        candidate_project=str(W/'td_project'/(new_name+'.al')),old_project_unchanged=True,
        new_synthesis_and_route_required=True,board_verified=False)
    put(O/'manifest.json',json.dumps(manifest,indent=2))
    for name,digest in snapshot.items():assert hashlib.sha256(Path(name).read_bytes()).hexdigest()==digest,name
    print(json.dumps(manifest,indent=2))

if __name__=='__main__':main()
