"""Export deterministic TEST-ONLY network parameters, descriptors and loader ROM.

No training or recognition capability is implied by these seeded parameters.
Physical memory ABI: [oc_group][cin_group][local_cin][local_cout][ky][kx].
Each group reserves 16*16*k*k bytes; biases reserve 16 INT32 per output group.
"""
import argparse
import hashlib
import json
from pathlib import Path
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT/'sim/network12'
SPEC = [(3,8,3,1),(8,16,3,1),(16,32,3,1),(32,64,3,0),
        (64,16,1,0),(16,64,3,0),(64,16,1,0),(16,64,3,0),
        (64,16,1,0),(16,64,3,0),(64,32,1,0),(32,9,1,0)]


def write_hex(path, data, digits):
    path.write_text(''.join(f'{int(n):0{digits}x}\n' for n in data),encoding='ascii')


def export(seed=20260908):
    DEST.mkdir(exist_ok=True)
    rng=np.random.Generator(np.random.PCG64(seed))
    # Deliberately exceed the legacy 17-bit (512 KiB) parameter address range.
    # The new network wrapper uses the full 21-bit word-offset SDRAM interface.
    base_word=0x22000
    memory=bytearray(base_word*4)
    layers=[]
    descriptors=[]
    raw={}
    w,h=160,120
    for index,(ci,co,k,pool) in enumerate(SPEC):
        weights=rng.choice(np.array([-4,-3,-2,-1,1,2,3,4],dtype=np.int8),(co,ci,k,k))
        biases=rng.integers(-4096,24577,size=co,dtype=np.int32) if index<11 else \
               rng.integers(-1500,1501,size=co,dtype=np.int32)
        ogs,cgs=(co+15)//16,(ci+15)//16
        wb=len(memory)//4
        packed=bytearray(ogs*cgs*256*k*k)
        for oc in range(co):
            for ic in range(ci):
                offset=(((oc//16)*cgs+(ic//16))*256+(ic%16)*16+(oc%16))*k*k
                packed[offset:offset+k*k]=weights[oc,ic].tobytes()
        memory.extend(packed)
        bb=len(memory)//4
        bias_padded=np.zeros(ogs*16,dtype='<i4')
        bias_padded[:co]=biases
        memory.extend(bias_padded.tobytes())
        ow,oh=(w//2,h//2) if pool else (w,h)
        shift=7 if index<11 else 0
        activation=1 if index<11 else 4
        words=[0x10000000|(activation<<20)|(k<<12)|(k<<8)|0x11,
               (0x122000 if pool else 0)|(1 if k==3 else 0),
               (co<<16)|ci,(h<<16)|w,(oh<<16)|ow,wb,bb,shift]
        descriptors.extend(words)
        layers.append(dict(id=index,cin=ci,cout=co,width=w,height=h,kernel=k,
            stride=1,padding=k//2,pool=bool(pool),out_width=ow,out_height=oh,
            activation='relu' if index<11 else 'integer_hardsigmoid',shift_bits=shift,
            weight_word_offset=wb,bias_word_offset=bb,
            weight_bytes=len(packed),bias_bytes=ogs*64,
            target='pong' if index%2==0 else 'ping',bank_words=ogs*ow*oh))
        raw[f'weight_{index}']=weights
        raw[f'bias_{index}']=biases
        w,h=ow,oh
    assert (w,h,SPEC[-1][1])==(20,15,9)
    ping=max([3600]+[l['bank_words'] for l in layers if l['target']=='ping'])
    pong=max(l['bank_words'] for l in layers if l['target']=='pong')
    assert ping<=8192 and pong<=8192 and len(memory)<=8*1024*1024
    # Seeded original RGB; independent integer indexing produces the agreed input.
    source=rng.integers(1,256,size=(600,1024,3),dtype=np.uint8)
    xs=((2*np.arange(160)+1)*1024)//320
    ys=((2*np.arange(94)+1)*600)//188
    image=np.zeros((3,120,160),dtype=np.uint8)
    image[:,13:107,:]=source[ys[:,None],xs[None,:],:].transpose(2,0,1)
    (DEST/'input.bin').write_bytes(image.tobytes())
    write_hex(DEST/'input.hex',image.ravel(),2)
    (DEST/'parameters.bin').write_bytes(memory)
    write_hex(DEST/'parameters16.hex',np.frombuffer(memory,dtype='<u2'),4)
    write_hex(DEST/'descriptors.hex',descriptors,8)
    np.savez_compressed(DEST/'logical_parameters.npz',**raw)
    manifest=dict(name='network12_integer_test',test_only=True,seed=seed,rng='PCG64',
        input_shape_whc=[160,120,3],output_shape_whc=[20,15,9],
        channels=['obj','dx','dy','w','h','cls0','cls1','cls2','cls3'],
        classes=['fire_extinguisher','exit_sign','yellow_warning_triangle','traffic_cone'],
        layer_count=12,param_addr_width=21,param_base_halfword=0xc00000,
        parameter_bytes=len(memory),parameter_halfwords=len(memory)//2,
        required_ping_bank_words=ping,required_pong_bank_words=pong,
        ping_bank_depth=4096,pong_bank_depth=5120,layers=layers,
        sha256={f:hashlib.sha256((DEST/f).read_bytes()).hexdigest() for f in
                ['input.bin','parameters.bin','descriptors.hex']})
    (DEST/'network.json').write_text(json.dumps(manifest,indent=2),encoding='utf-8')
    rom=['// Generated by sim/export_network12.py. TEST PARAMETERS ONLY.\n',
         '// Do not use as trained recognition weights or calibrated quantization.\n',
         'localparam integer MODEL_LAYER_COUNT = 12;\n',
         f'localparam integer MODEL_PARAMETER_HALFWORDS = {len(memory)//2};\n',
         'localparam integer MODEL_FINAL_WIDTH = 20;\n',
         'localparam integer MODEL_FINAL_HEIGHT = 15;\n',
         'localparam integer MODEL_FINAL_CHANNELS = 9;\n',
         'function [31:0] model_descriptor;\n    input [7:0] address;\n    begin\n',
         '        case (address)\n']
    rom.extend(f"            8'd{i}: model_descriptor = 32'h{v:08x};\n" for i,v in enumerate(descriptors))
    rom.append("            default: model_descriptor = 32'd0;\n        endcase\n    end\nendfunction\n")
    assert (ROOT/'sim/fixtures/npu_test_model_config.vh').read_text() == ''.join(rom), 'Test descriptor fixture differs; regression must not rewrite production RTL'
    return manifest


if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--seed',type=int,default=20260908)
    args=parser.parse_args()
    m=export(args.seed)
    print(json.dumps({k:m[k] for k in ['test_only','seed','layer_count','parameter_bytes',
        'required_ping_bank_words','required_pong_bank_words']}))
